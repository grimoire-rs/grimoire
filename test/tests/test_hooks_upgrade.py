"""Upgrading from the `sh`-shim launcher to the native one (C-N5, C-N12).

Hooks are experimental, so there is no migration engine: convergence deletes the
old `$GRIM_HOME/hooks/bin/grim-hook` shim once, rewrites every registration to the
new shape, and `launcher::ensure` writes the native launcher iff its bytes differ.

These tests do not depend on the launcher dispatching: the embedded launcher is
only compared as bytes.
"""
from __future__ import annotations

import hashlib
import json
import os
import subprocess
from pathlib import Path

import pytest

from src.helpers import make_artifact, write_config

pytestmark = pytest.mark.skipif(
    os.name == "nt", reason="the hook launcher and its registered command are POSIX-only in v1"
)

HOOK_TOML = """\
schema = 1
name = "shell-guard"
description = "Observes Bash tool calls before they run."

[[hooks]]
id = "guard"
event = "PreToolUse"
tier = "observer"
matcher = "Bash"
command = "sh guard.sh"
timeout = 5
"""

OLD_SHIM = (
    "#!/bin/sh\n"
    "# generated by grim — do not edit; `grim install` regenerates it\n"
    "G='/old/grim'\n"
    '[ -f "$G" ] && [ -x "$G" ] || exit 0\n'
    'exec "$G" hook "$@"\n'
)


def _armed(grim_at, project_dir: Path, unique_repo: str):
    hook = make_artifact(
        f"{unique_repo}/shell-guard",
        "hook",
        {"shell-guard/hook.toml": HOOK_TOML, "shell-guard/guard.sh": "#!/bin/sh\ncat > /dev/null\nprintf '{}'\n"},
        tag="1",
    )
    write_config(project_dir, hooks={"shell-guard": hook.fq})
    runner = grim_at(project_dir)
    runner.run("config", "set", "options.experimental.hooks", "true")
    runner.run("lock")
    runner.run("install", "--trust-hooks")
    return runner


def _settings(project_dir: Path) -> Path:
    return project_dir / ".claude" / "settings.local.json"


def _elements(project_dir: Path) -> list[dict]:
    hooks = json.loads(_settings(project_dir).read_text())["hooks"]
    return [e for groups in hooks.values() for g in groups for e in g["hooks"] if "grim-hook" in json.dumps(e)]


def _seed_old_registration(project_dir: Path, shim: Path) -> str:
    """Rewrite every grim registration in `project_dir` to the pre-launcher 5-line `sh` string."""
    command = (
        f"L='{shim}'\n"
        '[ -f "$L" ] && [ -x "$L" ] || exit 0\n'
        '"$L" run --client claude --event PreToolUse --table /old/dispatch.json --root deadbeef\n'
        "s=$?\n"
        'case "$s" in 0) exit 0 ;; *) exit 0 ;; esac'
    )
    settings = json.loads(_settings(project_dir).read_text())
    for groups in settings["hooks"].values():
        for group in groups:
            for element in group["hooks"]:
                if "grim-hook" in json.dumps(element):
                    element.pop("args", None)
                    element["command"] = command
    _settings(project_dir).write_text(json.dumps(settings))
    return command


def test_s003_the_old_shim_is_deleted_and_the_registration_rewritten(
    grim_at, project_dir: Path, registry: str, unique_repo: str
) -> None:
    """S-003: an install over a pre-native layout removes the shim and re-points the
    registration at `$GRIM_HOME/hooks/grim-hook`."""
    runner = _armed(grim_at, project_dir, unique_repo)
    hooks = Path(runner.grim_home) / "hooks"
    launcher = hooks / "grim-hook"
    assert launcher.is_file()

    # Pre-seed the old layout: the shim, and a registration that names it.
    shim = hooks / "bin" / "grim-hook"
    shim.parent.mkdir(parents=True, exist_ok=True)
    shim.write_text(OLD_SHIM)
    shim.chmod(0o755)
    _seed_old_registration(project_dir, shim)

    runner.run("install", "--trust-hooks")

    assert not shim.exists(), "the old shim survived convergence"
    elements = _elements(project_dir)
    assert len(elements) == 1, elements
    rendered = json.dumps(elements[0])
    assert str(launcher) in rendered, rendered
    assert "bin/grim-hook" not in rendered, rendered


def _publish_marking_guard(unique_repo: str, name: str, marker: Path):
    """A hook whose payload records that it ran, so a silent no-op can be told from a fire."""
    return make_artifact(
        f"{unique_repo}/{name}",
        "hook",
        {
            "shell-guard/hook.toml": HOOK_TOML,
            "shell-guard/guard.sh": f"#!/bin/sh\ncat > /dev/null\ntouch '{marker}'\nprintf '{{}}'\n",
        },
        tag="1",
    )


def test_s003_a_workspace_not_revisited_keeps_its_old_registration_and_does_not_fire(
    grim_at, tmp_path: Path, registry: str, unique_repo: str
) -> None:
    """S-003, workspace B: after an upgrade only the workspace `grim install` revisits is
    rewritten. B keeps the old 5-line string, whose shim guard finds no shim, exits 0 and runs
    nothing, until `grim install` runs in B."""
    marker_a, marker_b = tmp_path / "ran-a", tmp_path / "ran-b"
    dirs = {}
    for name, marker in (("a", marker_a), ("b", marker_b)):
        project = tmp_path / f"project-{name}"
        (project / ".claude").mkdir(parents=True)
        write_config(project, hooks={"shell-guard": _publish_marking_guard(unique_repo, f"guard-{name}", marker).fq})
        runner = grim_at(project)
        runner.run("config", "set", "options.experimental.hooks", "true")
        runner.run("lock")
        runner.run("install", "--trust-hooks")
        dirs[name] = (project, runner)
    (project_a, runner_a), (project_b, runner_b) = dirs["a"], dirs["b"]

    hooks = Path(runner_a.grim_home) / "hooks"
    shim = hooks / "bin" / "grim-hook"
    shim.parent.mkdir(parents=True, exist_ok=True)
    shim.write_text(OLD_SHIM)
    shim.chmod(0o755)
    _seed_old_registration(project_a, shim)
    old_b = _seed_old_registration(project_b, shim)

    runner_a.run("install", "--trust-hooks")

    assert not shim.exists(), "revisiting A must delete the shim every workspace's old string names"
    (element_a,) = _elements(project_a)
    assert str(hooks / "grim-hook") in json.dumps(element_a), element_a
    (element_b,) = _elements(project_b)
    assert element_b["command"] == old_b, "B was not revisited, so its registration must not change"

    stdin = json.dumps({"hook_event_name": "PreToolUse", "tool_name": "Bash", "tool_input": {"command": "ls"}})
    env = {"PATH": os.environ.get("PATH", "")}
    old = subprocess.run(["/bin/sh", "-c", old_b], input=stdin, capture_output=True, text=True, env=env, check=False)
    assert (old.returncode, old.stdout) == (0, ""), old
    assert not marker_b.exists(), "B's old registration ran its payload"

    # Positive control: the same event through A's rewritten registration does fire.
    new = subprocess.run(
        ["/bin/sh", "-c", element_a["command"]], input=stdin, capture_output=True, text=True, env=env, check=False
    )
    assert new.returncode == 0, new
    assert marker_a.exists(), "A's rewritten registration never reached its payload; the negative above proves nothing"

    runner_b.run("install", "--trust-hooks")
    (healed,) = _elements(project_b)
    assert str(hooks / "grim-hook") in json.dumps(healed), healed


def test_ensure_leaves_a_current_launcher_alone_and_rewrites_foreign_bytes(
    grim_at, project_dir: Path, registry: str, unique_repo: str
) -> None:
    """C-N5: `ensure` writes iff the bytes differ — a second install keeps the inode and
    mtime, and a launcher holding other bytes is replaced."""
    runner = _armed(grim_at, project_dir, unique_repo)
    launcher = Path(runner.grim_home) / "hooks" / "grim-hook"
    embedded = launcher.read_bytes()
    before = launcher.stat()

    runner.run("install", "--trust-hooks")
    after = launcher.stat()
    assert (after.st_ino, after.st_mtime_ns) == (before.st_ino, before.st_mtime_ns)

    launcher.write_bytes(b"#!/bin/sh\n# foreign\n")
    launcher.chmod(0o755)
    runner.run("install", "--trust-hooks")
    assert launcher.read_bytes() == embedded
    assert os.access(launcher, os.X_OK)


def test_s008_a_directory_at_the_launcher_path_is_never_reaped(
    grim_at, project_dir: Path, registry: str, unique_repo: str
) -> None:
    """A directory left at the launcher path by an old `grim-hook` binding is user data.
    `ensure` refuses (`launcher-path-occupied`, reported at install time), writes
    nothing, and reaps nothing."""
    hook = make_artifact(
        f"{unique_repo}/shell-guard",
        "hook",
        {"shell-guard/hook.toml": HOOK_TOML, "shell-guard/guard.sh": "#!/bin/sh\ncat > /dev/null\nprintf '{}'\n"},
        tag="1",
    )
    write_config(project_dir, hooks={"shell-guard": hook.fq})
    runner = grim_at(project_dir)
    runner.run("config", "set", "options.experimental.hooks", "true")
    runner.run("lock")
    runner.run("hook", "allow")
    occupied = Path(runner.grim_home) / "hooks" / "grim-hook"
    (occupied / "payload").mkdir(parents=True)
    (occupied / "payload" / "hook.toml").write_text("old binding\n")

    install = runner.run("install", check=False)

    assert install.returncode == 0, install.stderr
    assert (occupied / "payload" / "hook.toml").read_text() == "old binding\n"
    assert sorted(p.name for p in occupied.iterdir()) == ["payload"]
    row = next(i for i in runner.json("status")["items"] if i["kind"] == "hook")
    assert row["state"] == "not-armed", row
    assert "something other than a file sits at the launcher's path" in install.stderr, install.stderr
    assert not _settings(project_dir).is_file() or "grim-hook" not in _settings(project_dir).read_text()


GATEKEEPER_TOML = HOOK_TOML.replace('tier = "observer"', 'tier = "gatekeeper"')


def test_s009_a_codex_upgrade_warns_once_and_status_reports_client_trust_pending(
    grim, grim_home: Path, registry: str, unique_repo: str
) -> None:
    """S-009: Codex keys its stored `/hooks` approval on the registration string, so a changed
    string leaves the gatekeeper untrusted. `grim install` names it in one warning, stays quiet
    when nothing changed, and `grim status` reports `client-trust-pending`."""
    home = Path(grim.home)
    (home / ".codex").mkdir(parents=True, exist_ok=True)
    hook = make_artifact(
        f"{unique_repo}/shell-guard",
        "hook",
        {"shell-guard/hook.toml": GATEKEEPER_TOML, "shell-guard/guard.sh": "#!/bin/sh\ncat > /dev/null\nprintf '{}'\n"},
        tag="1",
    )
    grim_home.mkdir(parents=True, exist_ok=True)
    (grim_home / "grimoire.toml").write_text(
        f'[hooks]\nshell-guard = "{hook.fq}"\n\n[options.experimental]\nhooks = true\n'
    )
    grim.run("lock", "--global")
    first = grim.run("install", "--global", "--trust-hooks")
    assert "/hooks" not in first.stderr, "a first install has no earlier approval to lose"

    surface = home / ".codex" / "hooks.json"
    launcher = str(grim_home / "hooks" / "grim-hook")
    registered = surface.read_text()
    assert launcher in registered, registered
    # Stand in for the pre-launcher registration string Codex last approved. grim only rewrites
    # a file whose digest it recorded, so the record follows the edit.
    stale = registered.replace(launcher, "/old/grim-hook")
    surface.write_text(stale)
    (record,) = (grim_home / "hooks" / "owned_files").iterdir()
    record.write_text(hashlib.sha256(stale.encode()).hexdigest())

    upgraded = grim.run("install", "--global", "--trust-hooks")
    warnings = [line for line in upgraded.stderr.splitlines() if "/hooks" in line]
    assert len(warnings) == 1, upgraded.stderr
    assert "shell-guard/guard" in warnings[0], warnings

    again = grim.run("install", "--global", "--trust-hooks")
    assert "/hooks" not in again.stderr, again.stderr

    (row,) = [i for i in grim.json("status", "--global")["items"] if i["kind"] == "hook"]
    assert row["state"] == "untrusted", row
    assert [a["cause"] for a in row["arming"]] == ["client-trust-pending"], row
